// 실제 호스트 렌더러와 에이전트를 통과한다. 외부 API는 격리 프리뷰 대역이다.
import assert from 'node:assert/strict';
import {mkdtemp} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
const {chromium}=await import(process.env.YOUTUBE_PLAYWRIGHT_MODULE||'playwright');
const base='http://127.0.0.1:8803',folder=await mkdtemp(join(tmpdir(),'youtube-workspace-ui-'));
const browser=await chromium.launch({headless:true});
try{
 const page=await browser.newPage({viewport:{width:1440,height:1100}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.addInitScript(()=>{window.cspViolations=[];document.addEventListener('securitypolicyviolation',e=>window.cspViolations.push(e.violatedDirective));});
 const ready=page.waitForResponse(r=>r.url().endsWith('/result'));
 await page.goto(base);await ready;
 const ui=page.frameLocator('#av-body iframe');
 await ui.locator('#query').waitFor();
 const frame=page.frames().find(f=>f.url().includes('/api/agent/canvas'));
 assert.equal(await ui.locator('.publication').count(),3);
 await ui.locator('#query').fill('references');
 await ui.locator('button[type=submit]').click();
 await ui.locator('.result').first().waitFor();
 assert.equal(await ui.locator('.result').count(),2);
 await ui.locator('.result').nth(1).click();
 assert.match(await ui.locator('#detail-title').innerText(),/<script>/);
 await ui.locator('#query').fill('Preserve my draft');
 await frame.evaluate(()=>window.retained='same-frame');
 await ui.locator('#summarize').click();
 await ui.locator('#summary').waitFor({state:'visible'});
 assert.match(await ui.locator('#summary').innerText(),/no captions retrieved/);
 assert.equal(await ui.locator('#query').inputValue(),'Preserve my draft');
 assert.equal(await frame.evaluate(()=>window.retained),'same-frame');
 await page.route('**/api/agent/action',route=>route.fulfill({json:{ok:false,error:'Test denial'}}),{times:1});
 await ui.locator('#info').click();
 await ui.locator('#notice').filter({hasText:'실행 결과를 확인하지 못했습니다'}).waitFor();
 assert.equal(await ui.locator('#info').isEnabled(),true);
 await ui.locator('#query').fill('error');
 await ui.locator('button[type=submit]').click();
 await ui.locator('#notice').filter({hasText:'Could not reach YouTube'}).waitFor();
 assert.ok(!(await ui.locator('#notice').innerText()).includes('SIMULATED_SECRET'));
 assert.equal(await ui.locator('#summary').isVisible(),true);
 assert.deepEqual(await frame.evaluate(()=>window.cspViolations),[]);
 await page.reload();await ui.locator('#summary').waitFor({state:'visible'});
 await page.waitForFunction(()=>getComputedStyle(document.querySelector('#agentview')).opacity==='1');
 await page.screenshot({path:join(folder,'desktop.png')});
 await page.setViewportSize({width:390,height:844});
 const mobileFrame=page.frames().find(f=>f.url().includes('/api/agent/canvas'));
 assert.equal(await mobileFrame.evaluate(()=>document.documentElement.scrollWidth-document.documentElement.clientWidth),0);
 await ui.locator('#query').scrollIntoViewIfNeeded();
 await page.screenshot({path:join(folder,'mobile.png')});
 await page.emulateMedia({reducedMotion:'reduce'});
 await ui.locator('#query').fill('empty');await ui.locator('button[type=submit]').click();
 await ui.locator('#empty-results').filter({hasText:'마지막 검색'}).waitFor();
 assert.equal(await ui.locator('.result').count(),0);
 assert.deepEqual(errors,[]);
 console.log(JSON.stringify({passed:true,checks:['search/select/summary','untrusted title as text','stable frame and draft','denied action and safe error','persistent state','CSP','mobile overflow','empty results'],screenshots:folder}));
}finally{await browser.close()}
